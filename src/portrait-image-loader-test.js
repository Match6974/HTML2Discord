import assert from 'node:assert/strict';
import {loadMaster,createImageLoader} from './portrait-image-loader.js';
const url='https://jp.ultrarumble.com/assets/Character/test.png';
const style=(id,u)=>({styleId:id,nameJa:id,ready:true,releaseStatus:'listed',imageUrl:u});
const master=[{nameJa:'テスト',characterId:1,styles:[style('Variant-0',url),style('Variant-1','invalid'),style('Variant-2',url+'2')]}];
const b=Buffer.alloc(24);Buffer.from('89504e470d0a1a0a','hex').copy(b);b.write('IHDR',12);b.writeUInt32BE(1,16);b.writeUInt32BE(1,20);
let calls=0;
const loader=createImageLoader(master,{delay:async()=>{},fetcher:async u=>{calls++;return {ok:true,arrayBuffer:async()=>u===url?b:Buffer.from('bad')};}});
assert.equal((await loader.images('テスト',null,'all')).length,1);
assert.equal(calls,4);
assert.equal((await loader.images('テスト',null,'all')).length,1);
assert.equal(calls,4);
assert.equal((await loader.images('missing',null,'all')).length,0);
assert.equal((await loader.images('テスト','missing','unknown')).length,0);
const fail=createImageLoader(master,{delay:async()=>{},fetcher:async()=>{throw Error('offline')}});
assert.deepEqual(await fail.images('テスト',null,'all'),[]);
const decode=createImageLoader(master,{delay:async()=>{},fetcher:async()=>({ok:true,arrayBuffer:async()=>b}),validate:async()=>{throw Error('decode failed')}});
assert.deepEqual(await decode.images('テスト','Variant-0','unknown'),[]);
const warnings=[];
assert.deepEqual(await loadMaster(['missing','backup'],warnings,async p=>{if(p==='missing')throw Error('missing');return JSON.stringify(master)}),master);
assert.deepEqual(await loadMaster(['missing'],warnings,async()=>{throw Error('missing')}),[]);
console.log('Portrait fallback tests passed');
